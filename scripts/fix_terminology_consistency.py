def build_rules(repo_root: Path) -> dict[str, list[Rule]]:
    """Return {variant_text: [(canonical_text, source_label, source_text)]}.

    Replacements are only safe when the segment source contains the matching
    JP term. Without that guard, short aliases such as "稀有" or place-name
    homophones can corrupt unrelated prose across the book.
    """
    rules: dict[str, list[Rule]] = {}

    cp_path = repo_root / "workspace" / "configs" / "character_profile.yaml"
    cp = yaml.safe_load(cp_path.read_text(encoding="utf-8"))
    for c in cp.get("characters", []) or []:
        target = (c.get("target_name") or "").strip()
        if not target:
            continue
        source = (c.get("name") or "").strip()
        for variant in c.get("forbidden", []) or []:
            variant = (variant or "").strip()
            if variant and variant != target:
                rules.setdefault(variant, []).append((target, f"character_profile:{c['name']}", source))

    store = GlossaryStore(repo_root / "workspace" / "configs" / "glossary.yaml")
    for entry in store.entries():
        if not (entry.locked and entry.approved_by_user):
            continue
        target = (entry.target_term or "").strip(BRACKETS).strip()
        if not target:
            continue
        variants = list(entry.aliases or [])
        variants.append(entry.source_term.strip(BRACKETS).strip())
        source = entry.source_term.strip(BRACKETS).strip()
        for variant in variants:
            variant = (variant or "").strip()
            if variant and variant != target:
                rules.setdefault(variant, []).append((target, f"glossary:{entry.source_term}", source))

    return rules


_GLOSS_RE = re.compile(r"([\w一-鿿À-ɏ·]{1,40})(?:[（(]\1[）)]|〔\1〕)")


def _collapse_redundant_gloss(text: str) -> str:
    """Collapse 'X（X）' / 'X〔X〕' left over when a kanji gloss and its katakana
    reading both normalize to the same canonical term (e.g. 蜾蠃（スガル）
    -> 斯加尔（斯加尔） -> 斯加尔)."""
    return _GLOSS_RE.sub(r"\1", text)


